import {createRequire} from 'node:module';
import fs from 'node:fs/promises';
const require = createRequire(import.meta.url);
console.log('正在构建 BugBoard 前端。');
const esbuild = require('esbuild');
await fs.mkdir('dist', {recursive:true});
await esbuild.build({entryPoints:['src/main.tsx'],bundle:true,outfile:'dist/app.js',format:'esm',jsx:'automatic',nodePaths:[process.env.NODE_PATH || 'node_modules'],minify:true});
const template = await fs.readFile('index.html', 'utf8');
await fs.writeFile('dist/index.html', template.replace('<script type="module" src="/src/main.tsx"></script>', '<script type="module" src="/app.js"></script>').replace('</head>', '<link rel="stylesheet" href="/app.css"></head>'));
await fs.cp('public', 'dist', {recursive: true});
